/**
 * Интервальная арифметика правила Конфликта: единственное место формулы
 * в исполняемом коде (ADR-0003, спецификация §5).
 */

/** Интервал: полуоткрытый `[start, end)` — касание границами не Конфликт. */
export interface Interval {
  /** Начало интервала, UTC-инстант. */
  start: Date
  /** Конец интервала, UTC-инстант; в интервал не включается. */
  end: Date
}

/**
 * Пересечение полуоткрытых интервалов [start, end): a.start < b.end &&
 * b.start < a.end (ADR-0003). Касание границами Конфликтом не считается:
 * встреча 10:00–10:30 и встреча 10:30–11:00 совместимы (спецификация §5).
 * Частичное наложение любых типов встреч — Конфликт.
 */
export function intervalsIntersect(a: Interval, b: Interval): boolean {
  return a.start.getTime() < b.end.getTime() && b.start.getTime() < a.end.getTime()
}
