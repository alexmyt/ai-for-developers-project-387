// Матрица правила Конфликта (спецификация §5, ADR-0003): полуоткрытые
// интервалы [start, end), касание границами конфликтом не считается.
// Время задаётся UTC-инстантами, московские хелперы не используются.
import { describe, expect, it } from 'vitest'
import { intervalsIntersect, type Interval } from '../src/index.js'

function interval(from: string, to: string): Interval {
  return { start: new Date(from), end: new Date(to) }
}

describe('пересечение полуоткрытых интервалов', () => {
  it('точное наложение — конфликт', () => {
    expect(
      intervalsIntersect(
        interval('2026-11-12T07:00:00Z', '2026-11-12T07:30:00Z'),
        interval('2026-11-12T07:00:00Z', '2026-11-12T07:30:00Z'),
      ),
    ).toBe(true)
  })

  it('частичное наложение — конфликт, даже у разных типов встреч', () => {
    // 10:00–11:00 (60 минут) и 10:30–11:00 (30 минут): пример из требований
    // (спецификация §5); московское время — UTC+3, поэтому 10:00Z→07:00Z.
    expect(
      intervalsIntersect(
        interval('2026-11-12T07:00:00Z', '2026-11-12T08:00:00Z'),
        interval('2026-11-12T07:30:00Z', '2026-11-12T08:00:00Z'),
      ),
    ).toBe(true)
  })

  it('вложение — конфликт', () => {
    expect(
      intervalsIntersect(
        interval('2026-11-12T07:00:00Z', '2026-11-12T08:00:00Z'),
        interval('2026-11-12T07:10:00Z', '2026-11-12T07:20:00Z'),
      ),
    ).toBe(true)
  })

  it('касание границами — не конфликт', () => {
    // 10:00–10:30 и 10:30–11:00 совместимы: следующая встреча может
    // начинаться ровно в момент окончания предыдущей (спецификация §5).
    expect(
      intervalsIntersect(
        interval('2026-11-12T07:00:00Z', '2026-11-12T07:30:00Z'),
        interval('2026-11-12T07:30:00Z', '2026-11-12T08:00:00Z'),
      ),
    ).toBe(false)
  })

  it('касание в другую сторону — не конфликт', () => {
    expect(
      intervalsIntersect(
        interval('2026-11-12T07:30:00Z', '2026-11-12T08:00:00Z'),
        interval('2026-11-12T07:00:00Z', '2026-11-12T07:30:00Z'),
      ),
    ).toBe(false)
  })

  it('непересекающиеся интервалы — не конфликт', () => {
    expect(
      intervalsIntersect(
        interval('2026-11-12T07:00:00Z', '2026-11-12T07:30:00Z'),
        interval('2026-11-12T08:00:00Z', '2026-11-12T08:30:00Z'),
      ),
    ).toBe(false)
  })

  it('непересекающиеся в другую сторону — не конфликт', () => {
    expect(
      intervalsIntersect(
        interval('2026-11-12T08:00:00Z', '2026-11-12T08:30:00Z'),
        interval('2026-11-12T07:00:00Z', '2026-11-12T07:30:00Z'),
      ),
    ).toBe(false)
  })
})
